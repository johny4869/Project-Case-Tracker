import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');

const url = process.env.SUPABASE_URL || '';
const key = process.env.SUPABASE_PUBLISHABLE_KEY || '';
const gitLogUrl = process.env.GIT_LOG_URL || 'data/git-log.json';
const ragReportUrl = process.env.RAG_REPORT_URL || 'RAG驗證結果報告.md';

if (!url || !key) {
  console.error('[gen-config] SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY are required.');
  process.exit(1);
}
if (key.startsWith('sb_secret_') || key.includes('service_role')) {
  console.error('[gen-config] Refusing to write a secret/service_role key into client config.');
  process.exit(1);
}

const content = `// Auto-generated by scripts/gen-config.mjs. Do not edit or commit.
export const SUPABASE_URL = ${JSON.stringify(url)};
export const SUPABASE_PUBLISHABLE_KEY = ${JSON.stringify(key)};
export const GIT_LOG_URL = ${JSON.stringify(gitLogUrl)};
export const RAG_REPORT_URL = ${JSON.stringify(ragReportUrl)};
`;

writeFileSync(resolve(root, 'config.js'), content, 'utf8');
console.log('[gen-config] Wrote config.js');
